/**
 * Writes the chart Argo CD deploys: `chart/` with `values.yaml` and `values-<environment>.yaml`
 * merged into one `values.yaml`, and both image versions pinned.
 *
 *   bun scripts/render-deployment.ts <environment> <version> [output directory]
 */
import { cp, mkdir, rm } from "node:fs/promises";
import { resolve } from "node:path";

type Values = Record<string, unknown>;

const isMap = (value: unknown): value is Values =>
  typeof value === "object" && value !== null && !Array.isArray(value);

function merge(base: Values, override: Values): Values {
  const merged = { ...base };
  for (const [key, value] of Object.entries(override)) {
    const current = merged[key];
    merged[key] = isMap(current) && isMap(value) ? merge(current, value) : value;
  }
  return merged;
}

const readValues = async (path: string) => Bun.YAML.parse(await Bun.file(path).text()) as Values;

export async function renderDeployment(
  environment: string,
  version: string,
  output: string,
): Promise<void> {
  const chart = resolve(import.meta.dir, "../chart");
  const values = merge(
    merge(
      await readValues(`${chart}/values.yaml`),
      await readValues(`${chart}/values-${environment}.yaml`),
    ),
    { version_api: version, version_web: version },
  );

  await rm(output, { recursive: true, force: true });
  await mkdir(output, { recursive: true });
  await cp(`${chart}/Chart.yaml`, `${output}/Chart.yaml`);
  await cp(`${chart}/templates`, `${output}/templates`, { recursive: true });
  await Bun.write(
    `${output}/values.yaml`,
    `# Generated by scripts/render-deployment.ts from chart/values.yaml and chart/values-${environment}.yaml.\n` +
      "# Do not edit: the next release overwrites this file.\n" +
      `${Bun.YAML.stringify(values, null, 2)}\n`,
  );
}

if (import.meta.main) {
  const [environment, version, output] = process.argv.slice(2);
  if (!environment || !version) {
    console.error("usage: bun scripts/render-deployment.ts <environment> <version> [output]");
    process.exit(1);
  }
  await renderDeployment(
    environment,
    version,
    resolve(output ?? `${import.meta.dir}/../chart_deployment/${environment}`),
  );
}
