#!/bin/sh
# JVM unit tests of the Android health plugin, run in the generated Gradle project under
# src-tauri/gen/android. `tauri android build` writes that project's tauri.settings.gradle and
# app/tauri.build.gradle.kts; when they are missing (fresh clone, CI) this writes the same two
# files, so the tests need a JDK and the Android SDK but no NDK or Rust Android targets.
set -eu
cd "$(dirname "$0")/.."
app_dir=$(pwd)
android_dir=src-tauri/gen/android

if [ ! -f "$android_dir/tauri.settings.gradle" ] || [ ! -f "$android_dir/app/tauri.build.gradle.kts" ]; then
  tauri_manifest=$(cargo metadata --format-version 1 --manifest-path Cargo.toml |
    jq -r '.packages[] | select(.name == "tauri") | .manifest_path')
  tauri_android="$(dirname "$tauri_manifest")/mobile/android"
  [ -d "$tauri_android" ] || { echo "Tauri Android library not found at $tauri_android" >&2; exit 1; }
  cat > "$android_dir/tauri.settings.gradle" <<EOF
// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
include ':tauri-android'
project(':tauri-android').projectDir = new File("$tauri_android")
include ':tauri-plugin-health'
project(':tauri-plugin-health').projectDir = new File("$app_dir/plugins/tauri-plugin-health/android")
EOF
  cat > "$android_dir/app/tauri.build.gradle.kts" <<'EOF'
// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
val implementation by configurations
dependencies {
  implementation("androidx.lifecycle:lifecycle-process:2.10.0")
  implementation(project(":tauri-android"))
  implementation(project(":tauri-plugin-health"))
}
EOF
fi

cd "$android_dir"
exec ./gradlew -q :tauri-plugin-health:testDebugUnitTest "$@"
